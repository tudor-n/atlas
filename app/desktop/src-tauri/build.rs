//! Tauri's build step, plus the shell-source digest (plan Task 9): the digest of this crate's own
//! source, computed exactly as the update step's `shell_source` does for the live copy, is baked
//! in as `ATLAS_SHELL_SOURCE`. The shell compares the two to notice a newer shell in the live
//! copy ("widget update available").
//!
//! The app manifest declares the widget's commands: `open_main` (phase 4.5: a row opens the main
//! window), `fit_widget` (its exact size) and `hide_widget` (its – button). That generates the
//! permissions `allow-open-main`, `allow-fit-widget` and `allow-hide-widget` (in
//! `permissions/autogenerated/`, git-ignored), which only `capabilities/widget.json` grants: the
//! main window has no capability, so no IPC.

#[path = "src/shell_source.rs"]
mod shell_source;

fn main() {
    let here = std::path::PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let digest = shell_source::digest(&here).unwrap_or_else(|e| {
        // An empty digest means "unknown": the shell then never says an update is available.
        println!("cargo:warning=shell source digest failed: {e}");
        String::new()
    });
    println!("cargo:rustc-env=ATLAS_SHELL_SOURCE={digest}");
    for path in ["Cargo.toml", "Cargo.lock", "build.rs", "tauri.conf.json", "src", "capabilities", "../dist"] {
        println!("cargo:rerun-if-changed={path}");
    }
    // The icons aren't in the digest, but tauri bakes them into the binary (window and tray icon):
    // a new icon must rebuild it (the launcher rebuilds after any live-copy commit).
    println!("cargo:rerun-if-changed=icons");
    let attributes = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(&["open_main", "fit_widget", "hide_widget"]));
    if let Err(e) = tauri_build::try_build(attributes) {
        panic!("tauri build step failed: {e:#}");
    }
}
